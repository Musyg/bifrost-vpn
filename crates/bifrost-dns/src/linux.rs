    /// Le defaut mesure sur essai-linux le 20 aout 2026, et le plus couteux
    /// des trois: un daemon MORT sans restaurer, puis un autre qui demarre.
    ///
    /// La garde qui existait ne protegeait que le meme processus. Le suivant
    /// relevait le fichier de Bifrost comme etant l'original, et la sauvegarde
    /// finissait par contenir "genere par bifrost": plus aucune deconnexion,
    /// meme propre, ne pouvait alors rendre son resolveur a la machine.
    #[test]
    fn un_daemon_mort_ne_fait_pas_de_son_fichier_l_original() {
        let bac = Jetable::neuf();
        bac.gere_par_un_service("nameserver 192.168.1.1\n");

        // Le premier daemon pose le resolveur du tunnel, puis meurt: `restore`
        // n'est jamais appele, ce qui est le comportement VOULU de
        // `on_shutdown` - un daemon qui meurt laisse le systeme ferme.
        let mut premier = bac.gestionnaire();
        premier.apply("wg0", &policy()).unwrap();
        drop(premier);

        // Le suivant demarre et retrouve le fichier de son predecesseur.
        let mut second = bac.gestionnaire();
        second.apply("wg0", &policy()).unwrap();
        second.restore().unwrap();

        assert!(
            fs::symlink_metadata(bac.resolv())
                .unwrap()
                .file_type()
                .is_symlink(),
            "le daemon suivant a pris le fichier du precedent pour l'etat d'origine"
        );
    }

    /// La forme, et pas seulement le contenu: c'est elle qui devait survivre.
