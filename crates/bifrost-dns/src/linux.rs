    /// Repertoire jetable, sans dependance de test supplementaire.
    struct Jetable(PathBuf);

    impl Jetable {
        fn neuf() -> Self {
            let p = std::env::temp_dir().join(format!(
                "bifrost-dns-{}-{}",
                std::process::id(),
                SUITE.fetch_add(1, Ordering::Relaxed)
            ));
            let _ = fs::remove_dir_all(&p);
            fs::create_dir_all(&p).unwrap();
            Self(p)
        }

        fn resolv(&self) -> PathBuf {
            self.0.join("resolv.conf")
        }

        /// Un gestionnaire de reseau branche comme sur une vraie machine: un
        /// fichier dans un repertoire de service, et un lien vers lui.
        fn gere_par_un_service(&self, contenu: &str) -> PathBuf {
            let cible = self.0.join("run/stub-resolv.conf");
            fs::create_dir_all(cible.parent().unwrap()).unwrap();
            fs::write(&cible, contenu).unwrap();
            std::os::unix::fs::symlink("run/stub-resolv.conf", self.resolv()).unwrap();
            cible
        }

        fn gestionnaire(&self) -> ResolvConfDns {
            ResolvConfDns::new(self.resolv(), self.0.join("var"))
        }

        fn mode(&self) -> u32 {
            fs::symlink_metadata(self.resolv())
                .unwrap()
                .permissions()
                .mode()
                & 0o777
        }
    }

    impl Drop for Jetable {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

