    /// systeme basculerait sur une resolution en clair sans rien dire, et
    /// justement le jour ou le chiffrement servait.
    #[test]
    fn le_resolveur_embarque_n_a_aucun_secours_en_clair() {
        let c = resolv_conf_contents(&DnsPolicy {
            embarque: true,
            anti_telemetrie: bifrost_core::config::ProfilTelemetrie::Aucun,
            ..policy()
        });
        assert_eq!(
            c.matches("nameserver").count(),
            1,
            "un resolveur de secours accompagne le resolveur chiffre\n{c}"
        );
        for amont in &policy().upstream {
            assert!(
                !c.contains(&amont.to_string()),
                "l'amont {amont} reste joignable en clair\n{c}"
            );
        }
    }

